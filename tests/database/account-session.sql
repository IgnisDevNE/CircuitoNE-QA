-- Disposable SQL regression: no private identity projection may cross accounts.
begin;
create function pg_temp.assert_true(value boolean, message text) returns void language plpgsql as $$ begin if value is distinct from true then raise exception '%', message; end if; end $$;
grant execute on function pg_temp.assert_true(boolean,text) to authenticated;
insert into auth.users(id,email,email_confirmed_at,phone,phone_confirmed_at) values
('81000000-0000-4000-8000-000000000001','session-a@example.invalid',now(),'5581990000081',now()),
('81000000-0000-4000-8000-000000000002','session-b@example.invalid',now(),'5581990000082',now()),
('81000000-0000-4000-8000-000000000003','session-incomplete@example.invalid',null,null,null);
set local role authenticated;
select set_config('request.jwt.claims','{"sub":"81000000-0000-4000-8000-000000000001","role":"authenticated"}',true);
select public.complete_registration('{"name":"Conta A sintética","cpf":"52998224725","birth_date":"1990-01-01","city":"Recife","state_code":"PE","phone_is_whatsapp":true}','{"kind":"member","name":"Atuação A"}','82000000-0000-4000-8000-000000000001');
select pg_temp.assert_true(public.get_account_session()=jsonb_build_object('id','81000000-0000-4000-8000-000000000001','name','Conta A sintética','state','active','reason',null),'Session must expose only the current minimal account');
select set_config('request.jwt.claims','{"sub":"81000000-0000-4000-8000-000000000002","role":"authenticated"}',true);
select public.complete_registration('{"name":"Conta B sintética","cpf":"12345678909","birth_date":"1990-01-01","city":"Recife","state_code":"PE","phone_is_whatsapp":true}','{"kind":"member","name":"Atuação B"}','82000000-0000-4000-8000-000000000002');
select pg_temp.assert_true(public.get_account_session()->>'name'='Conta B sintética','B must not see A');
reset role;
update auth.users set banned_until=now()+interval '1 hour' where id='81000000-0000-4000-8000-000000000001';
set local role authenticated;
select set_config('request.jwt.claims','{"sub":"81000000-0000-4000-8000-000000000001","role":"authenticated"}',true);
select pg_temp.assert_true(public.get_account_session() is null,'Auth ban must deny account projection');
reset role;
update auth.users set banned_until=now()-interval '1 hour',email_confirmed_at=null where id='81000000-0000-4000-8000-000000000001';
set local role authenticated;
select pg_temp.assert_true(public.get_account_session()->>'state'='incomplete','Unconfirmed email must not grant active access');
reset role;
update auth.users set email_confirmed_at=now(),phone_confirmed_at=null where id='81000000-0000-4000-8000-000000000001';
set local role authenticated;
select pg_temp.assert_true(public.get_account_session()->>'state'='incomplete','Unconfirmed phone must not grant active access');
reset role;
update auth.users set phone_confirmed_at=now() where id='81000000-0000-4000-8000-000000000001';
set local role authenticated;
select pg_temp.assert_true(public.get_account_session()->>'state'='active','Expired ban must preserve current application state');
reset role;
update private.account_details set state='suspended',state_reason='Revisão sintética' where user_id='81000000-0000-4000-8000-000000000001';
set local role authenticated;
select set_config('request.jwt.claims','{"sub":"81000000-0000-4000-8000-000000000001","role":"authenticated"}',true);
select pg_temp.assert_true(public.get_account_session()->>'state'='suspended' and public.get_account_session()->>'reason'='Revisão sintética','Suspension reason must remain available to its owner');
reset role;
update auth.users set phone_confirmed_at=null where id='81000000-0000-4000-8000-000000000001';
set local role authenticated;
select pg_temp.assert_true(public.get_account_session()->>'state'='suspended','Missing confirmation must not hide suspension/support state');
select set_config('request.jwt.claims','{"sub":"81000000-0000-4000-8000-000000000003","role":"authenticated"}',true);
select pg_temp.assert_true(public.get_account_session()->>'state'='incomplete','Auth-only onboarding must not become active');
select set_config('request.jwt.claims','{}',true);
select pg_temp.assert_true(public.get_account_session() is null,'No identity must not get an account');
reset role;
update private.account_details set state='deletion_pending' where user_id='81000000-0000-4000-8000-000000000002';
update auth.users set email_confirmed_at=null where id='81000000-0000-4000-8000-000000000002';
set local role authenticated;
select set_config('request.jwt.claims','{"sub":"81000000-0000-4000-8000-000000000002","role":"authenticated"}',true);
select pg_temp.assert_true(public.get_account_session()->>'state'='deletion_pending','Deletion must not grant active access');
reset role;
update auth.users set deleted_at=now() where id='81000000-0000-4000-8000-000000000002';
set local role authenticated;
select pg_temp.assert_true(public.get_account_session() is null,'Deleted identity must not return data');
reset role;
select pg_temp.assert_true(not has_function_privilege('anon','public.get_account_session()','EXECUTE'),'Anonymous account projection exposed');
select pg_temp.assert_true(not has_function_privilege('service_role','public.get_account_session()','EXECUTE'),'Service role must not be an application identity');
select pg_temp.assert_true(not has_table_privilege('authenticated','private.account_details','SELECT'),'Private account table exposed');
rollback;
